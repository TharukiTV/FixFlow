import {test, expect} from '@playwright/test'
test('sample preview, stale input, service failure, and ticket submission',async({page})=>{
  await page.route('**/api/auth/me',route=>route.fulfill({json:{email:'test@example.test',name:'Test',role:'USER'}}))
  await page.route('**/api/auth/csrf',route=>route.fulfill({json:{headerName:'X-CSRF-TOKEN',token:'test'}}))
  await page.route('**/api/incidents',route=>route.fulfill({json:route.request().method()==='POST'?{id:1,...route.request().postDataJSON(),status:'OPEN',createdAt:'2026-09-12T00:00:00Z',assignedTechnician:null}:[]}))
  await page.route('**/api/analysis',route=>route.fulfill({json:{mode:'GEMINI',category:'IT',priority:'MEDIUM',summary:'Example IT report.',notice:'AI suggestion; requires review.'}}))
  await page.goto('/')
  const preview=page.getByRole('button',{name:'Analyze with Gemini'})
  await expect(preview).toBeDisabled()
  await page.locator('#description').fill('Wi-Fi not working')
  await page.getByLabel('Where is it?').fill('Lab 2')
  await preview.click()
  await expect(page.getByText('Gemini AI suggestion',{exact:true})).toBeVisible()
  await page.locator('#description').fill('Changed issue')
  await expect(page.getByText('Gemini AI suggestion',{exact:true})).toHaveCount(0)
  await page.unroute('**/api/analysis')
  await page.route('**/api/analysis',route=>route.fulfill({status:503}))
  await preview.click()
  await expect(page.getByText('AI analysis is unavailable. You can still submit your ticket.')).toBeVisible()
  await page.getByRole('button',{name:'Submit issue'}).click()
  await expect(page.getByText('Ticket INC-1 created successfully.')).toBeVisible()
})
